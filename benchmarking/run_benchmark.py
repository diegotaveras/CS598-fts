#!/usr/bin/env python3
import argparse
import asyncio
import json
import sys
import time
from pathlib import Path

import grpc

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from rag import rag_pb2, rag_pb2_grpc


def parse_args():
    parser = argparse.ArgumentParser(
        description="Inject benchmark JSONL rows into the distributed RAG workers."
    )
    parser.add_argument(
        "--benchmark",
        default="benchmarking/benchmark.jsonl",
        help="Benchmark JSONL generated by benchmarking/generate_benchmark_jsonl.py.",
    )
    parser.add_argument(
        "--config",
        default="deploy/vm_workers.json",
        help="Worker deployment config used to resolve node IDs to endpoints.",
    )
    parser.add_argument(
        "--output",
        default="benchmarking/dispatch_events.jsonl",
        help="JSONL file for benchmark-engine dispatch events.",
    )
    parser.add_argument("--limit", type=int, default=0, help="Optional max rows to run.")
    parser.add_argument(
        "--start-offset",
        type=int,
        default=0,
        help="Skip this many benchmark rows before running.",
    )
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument("--max-hops", type=int, default=4)
    parser.add_argument(
        "--mode",
        choices=["chain_hop", "local_only", "broadcast"],
        default="",
        help=(
            "Optional routing mode override for every row. "
            "If omitted, each row's mode field is used, defaulting to chain_hop."
        ),
    )
    parser.add_argument(
        "--request-timeout",
        type=float,
        default=10.0,
        help="gRPC RouteQuery timeout in seconds.",
    )
    parser.add_argument(
        "--delay-seconds",
        type=float,
        default=0.0,
        help="Delay between benchmark rows.",
    )
    parser.add_argument(
        "--final-wait-seconds",
        type=float,
        default=0.0,
        help="Optional wait after the last dispatch to let final answers arrive.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Resolve and print dispatches without sending gRPC requests.",
    )
    return parser.parse_args()


def endpoint(node: dict, default_port: int) -> str:
    if node.get("endpoint"):
        return str(node["endpoint"])
    addr = str(node["addr"])
    port = int(node.get("port", default_port))
    if ":" in addr:
        return addr
    return f"{addr}:{port}"


def expand_nodes(config: dict) -> list[dict]:
    if config.get("nodes"):
        return config["nodes"]

    vms = config.get("vms", [])
    workers_per_vm = int(config.get("workers_per_vm", 1))
    total_workers = config.get("total_workers")
    total_workers = int(total_workers) if total_workers is not None else len(vms) * workers_per_vm
    base_port = int(config.get("port", 9100))
    listen_port = int(config.get("container_port", config.get("listen_port", 9100)))

    nodes = []
    worker_number = 1
    for vm in vms:
        for local_index in range(workers_per_vm):
            if worker_number > total_workers:
                return nodes
            host_port = int(vm.get("base_port", base_port)) + local_index
            nodes.append(
                {
                    "id": f"node{worker_number}",
                    "addr": vm["addr"],
                    "port": host_port,
                    "listen_port": listen_port,
                    "vm_id": vm.get("id", ""),
                    "local_worker_index": local_index,
                }
            )
            worker_number += 1
    return nodes


def load_endpoint_map(config_path: Path):
    config = json.loads(config_path.read_text(encoding="utf-8"))
    default_port = int(config.get("port", 9100))
    nodes = expand_nodes(config)
    return {
        node["id"]: {
            "endpoint": endpoint(node, default_port),
            "vm_id": node.get("vm_id", ""),
        }
        for node in nodes
    }


def iter_rows(path: Path, start_offset: int, limit: int):
    emitted = 0
    with path.open(encoding="utf-8") as handle:
        for index, line in enumerate(handle):
            if index < start_offset:
                continue
            if limit and emitted >= limit:
                break
            line = line.strip()
            if not line:
                continue
            emitted += 1
            yield json.loads(line)


def now_event(event: str, **fields):
    return {
        "event": event,
        "ts_unix": time.time(),
        "ts_monotonic": time.monotonic(),
        **fields,
    }


def append_jsonl(path: Path, payload: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(payload, sort_keys=True) + "\n")


def mode_max_hops(mode: str, default_max_hops: int):
    if mode == "local_only" or mode == "broadcast":
        return 1
    if mode != "chain_hop":
        raise ValueError(
            f"Unsupported benchmark mode={mode!r}. "
            "Supported runner modes: chain_hop, local_only, broadcast."
        )
    return default_max_hops


async def send_route_query(endpoint_addr: str, row: dict, coordinator_addr: str, top_k: int, max_hops: int, timeout: float):
    request = rag_pb2.RouteQueryRequest(
        query_id=row["query_id"],
        query=row["question"],
        top_k=top_k,
        coordinator_addr=coordinator_addr,
        curr_hop=0,
        max_hops=max_hops,
    )
    async with grpc.aio.insecure_channel(endpoint_addr) as channel:
        stub = rag_pb2_grpc.RagServiceStub(channel)
        return await stub.RouteQuery(request, timeout=timeout)


async def dispatch_row(row: dict, endpoint_by_worker: dict, args, output_path: Path):
    mode = args.mode or row.get("mode", "chain_hop")
    initiator = row["initiator_worker"]
    if initiator not in endpoint_by_worker:
        raise KeyError(f"Unknown initiator_worker={initiator!r}")

    initiator_endpoint = endpoint_by_worker[initiator]["endpoint"]
    max_hops = mode_max_hops(mode, args.max_hops)
    targets = [initiator]
    if mode == "broadcast":
        targets = sorted(endpoint_by_worker, key=lambda worker: int(worker[4:]) if worker.startswith("node") and worker[4:].isdigit() else worker)

    append_jsonl(
        output_path,
        now_event(
            "dispatch_started",
            query_id=row["query_id"],
            logical_query_id=row.get("logical_query_id", row["query_id"]),
            mode=mode,
            initiator_worker=initiator,
            initiator_endpoint=initiator_endpoint,
            target_workers=targets,
            max_hops=max_hops,
        ),
    )

    started = time.monotonic()
    statuses = []
    for target in targets:
        target_endpoint = endpoint_by_worker[target]["endpoint"]
        if args.dry_run:
            statuses.append({"worker_id": target, "endpoint": target_endpoint, "status": "dry_run"})
            continue
        try:
            reply = await send_route_query(
                target_endpoint,
                row,
                coordinator_addr=initiator_endpoint,
                top_k=args.top_k,
                max_hops=max_hops,
                timeout=args.request_timeout,
            )
            statuses.append(
                {
                    "worker_id": target,
                    "endpoint": target_endpoint,
                    "status": "ok",
                    "reply_worker_id": reply.worker_id,
                    "candidate_count": len(reply.candidates),
                }
            )
        except Exception as exc:
            statuses.append(
                {
                    "worker_id": target,
                    "endpoint": target_endpoint,
                    "status": "error",
                    "error": str(exc),
                }
            )

    append_jsonl(
        output_path,
        now_event(
            "dispatch_completed",
            query_id=row["query_id"],
            logical_query_id=row.get("logical_query_id", row["query_id"]),
            mode=mode,
            initiator_worker=initiator,
            elapsed_seconds=time.monotonic() - started,
            statuses=statuses,
        ),
    )


async def main_async():
    args = parse_args()
    output_path = Path(args.output)
    endpoint_by_worker = load_endpoint_map(Path(args.config))
    rows = list(iter_rows(Path(args.benchmark), args.start_offset, args.limit))
    print(f"loaded {len(rows)} benchmark rows")

    for index, row in enumerate(rows, start=1):
        print(
            f"[{index}/{len(rows)}] {row['query_id']} "
            f"mode={args.mode or row.get('mode', 'chain_hop')} "
            f"initiator={row['initiator_worker']}"
        )
        await dispatch_row(row, endpoint_by_worker, args, output_path)
        if args.delay_seconds > 0:
            await asyncio.sleep(args.delay_seconds)

    if args.final_wait_seconds > 0:
        print(f"waiting {args.final_wait_seconds}s for final answers")
        await asyncio.sleep(args.final_wait_seconds)


def main():
    asyncio.run(main_async())


if __name__ == "__main__":
    main()
